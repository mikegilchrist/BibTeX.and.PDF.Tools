# Purpose:      Make an n-up (2x1, 2x2, 3x2, ...) version of a PDF
#
# Layout is selected by the name used to invoke the script: the file is
# symlinked as make.2x1.sh, make.2x2.sh, make.2x2L.sh, make.2x3.sh,
# make.3x2.sh, make.3x3.sh, make.4x1.sh, make.4x3.sh, make.5x3.sh, and the
# case block below dispatches on "$(basename $0)".
#
# NOTE on the layout labels: in this script the label is ROWSxCOLS-ish and
# does not match pdfnup's COLSxROWS convention.  E.g. make.2x3.sh sets
# COL=3, ROW=2, whereas "pdfnup --nup 2x3" means 2 columns by 3 rows.
#
# When invoked as *.and.link.pdf.sh the output is moved to ~/References/
# and symlinked back into the current directory.
#
# Usage:        make.<layout>.sh [--no-recompress] [pdfxup options] FILE.pdf
# Input:        A PDF file (last argument).  Any earlier arguments are
#               passed through to pdfxup.
# Output:       FILE-<layout>.pdf in the current directory
#
# Options:
#   --no-recompress   Skip the ghostscript pass (see below)
#
# Ghostscript pass (added 1.1.0; moved to a shared helper in 1.2.0):
#   pdfxup inflates output 15-60x on PDFs exported from ODP slides.  A
#   ghostscript rewrite recovers the size with the crop intact.  The full
#   explanation and the safety guards live in pdf.recompress.sh, which this
#   script sources.  Opt out with --no-recompress or PDFTOOLS_NO_RECOMPRESS;
#   override the quality preset with PDFTOOLS_GS_SETTING.
#
# Requirements:
#   - pdfxup (TeX Live package "pdfxup"), pdfinfo, pdfcrop
#   - pdf.recompress.sh alongside this script
#   - gs (optional; without it the output is left uncompressed)
#
# AI Model:     Claude Opus 5
